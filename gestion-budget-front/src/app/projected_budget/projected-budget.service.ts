import { HttpClient, HttpParams } from '@angular/common/http';
import { inject, Injectable, signal } from '@angular/core';
import { catchError, Observable, tap, throwError } from 'rxjs';
import { environment } from '../../environments/environment';
import { Transaction } from '../transaction/transaction.model';
import { ProjectedBudgetItems } from './projected-budget-items.model';
import { ProjectedBudgetPeriod } from './projected-budget-period.model';
import {
  ProjectedBudgetInitResponseDto,
  SuggestedPeriodDataDto,
} from './projected-budget-response-dto.model';

@Injectable({
  providedIn: 'root',
})
export class ProjectedBudgetService {
  private readonly http = inject(HttpClient);

  private readonly apiUrl = `${environment.apiUrl}/projected_budget`;
  readonly activePeriod = signal<ProjectedBudgetPeriod | undefined>(undefined);
  readonly budgetItems = signal<ProjectedBudgetItems[]>([]);
  readonly toolboxTransactions = signal<Transaction[]>([]);
  readonly isLoading = signal<boolean>(false);

  getProjectedBudgetItems(
    accountId: number,
    month: number,
    year: number,
  ): Observable<ProjectedBudgetItems[]> {
    return this.http
      .get<ProjectedBudgetItems[]>(`${this.apiUrl}/items`, {
        params: { accountId, month, year },
      })
      .pipe(
        tap((data) => {
          this.budgetItems.set(data);
        }),
      );
  }
  createProjectedBudgetPeriod(
    accountId: number,
    month: number,
    year: number,
    cloneFromId?: number,
  ): Observable<ProjectedBudgetInitResponseDto | null> {
    this.isLoading.set(true);
    const params = new HttpParams()
      .set('accountId', accountId)
      .set('month', month)
      .set('year', year)
      .set('cloneFromId', cloneFromId || '');

    return this.http.post<ProjectedBudgetInitResponseDto>(this.apiUrl, null, { params }).pipe(
      tap((response: ProjectedBudgetInitResponseDto) => {
        this.activePeriod.set(response.period);
        this.toolboxTransactions.set(response.data.suggestedTransactions);
        this.budgetItems.set(response.data.autoGeneratedItems);
        this.isLoading.set(false);
      }),
      catchError((error) => {
        this.isLoading.set(false);
        return throwError(() => error);
      }),
    );
  }

  getAvailablePeriodsForDuplication(accountId: number): Observable<ProjectedBudgetPeriod[]> {
    return this.http.get<ProjectedBudgetPeriod[]>(`${this.apiUrl}/periods`, {
      params: { accountId },
    });
  }
  executeDuplicationItems(
    cloneFromId: number,
    periodIdCible: number,
  ): Observable<ProjectedBudgetItems[]> {
    this.isLoading.set(true);
    const params = new HttpParams()
      .set('periodIdModel', cloneFromId)
      .set('periodIdCible', periodIdCible);

    return this.http
      .put<ProjectedBudgetItems[]>(`${this.apiUrl}/duplicateItems`, null, { params })
      .pipe(
        tap((updatedItems) => {
          this.budgetItems.set(updatedItems);
          this.isLoading.set(false);
        }),
        catchError((error) => {
          this.isLoading.set(false);
          return throwError(() => error);
        }),
      );
  }

  fetchSuggestedTransactions(
    accountId: number,
    month: number,
    year: number,
  ): Observable<SuggestedPeriodDataDto> {
    return this.http
      .get<SuggestedPeriodDataDto>(`${this.apiUrl}/suggestions`, {
        params: { accountId, month, year },
      })
      .pipe(
        tap((data) => {
          this.toolboxTransactions.set(data.suggestedTransactions);
          if (this.budgetItems().length == 0 && data.autoGeneratedItems.length != 0)
            this.budgetItems.set(data.autoGeneratedItems);
        }),
      );
  }

  saveProjectedBudgetItems(): Observable<ProjectedBudgetItems[]> {
    const period = this.activePeriod();
    const items = this.budgetItems();

    if (!period) {
      return throwError(() => new Error('Aucune période budgétaire active à enregistrer.'));
    }

    this.isLoading.set(true);

    return this.http.put<ProjectedBudgetItems[]>(`${this.apiUrl}/${period.id}/items`, items).pipe(
      tap((updatedItems) => {
        this.budgetItems.set(updatedItems);
        this.isLoading.set(false);
      }),
      catchError((error) => {
        this.isLoading.set(false);
        return throwError(() => error);
      }),
    );
  }

  deleteProjectedBudgetPeriod(): Observable<void> {
    const period = this.activePeriod();

    if (!period) {
      return throwError(() => new Error('Aucune période active à supprimer.'));
    }

    this.isLoading.set(true);

    return this.http.delete<void>(`${this.apiUrl}/${period.id}`).pipe(
      tap(() => {
        this.activePeriod.set(undefined);
        this.budgetItems.set([]);
        this.toolboxTransactions.set([]);
        this.isLoading.set(false);
      }),
      catchError((error) => {
        this.isLoading.set(false);
        return throwError(() => error);
      }),
    );
  }
}
