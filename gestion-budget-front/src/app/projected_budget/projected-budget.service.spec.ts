import { HttpErrorResponse, provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { TestBed } from '@angular/core/testing';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { environment } from '../../environments/environment';
import { Account, AccountType } from '../settings/account/account.model';
import { Transaction } from '../transaction/transaction.model';
import { ProjectedBudgetCategoryType, ProjectedBudgetItems } from './projected-budget-items.model';
import { ProjectedBudgetPeriod } from './projected-budget-period.model';
import {
  ProjectedBudgetInitResponseDto,
  SuggestedPeriodDataDto,
} from './projected-budget-response-dto.model';
import { ProjectedBudgetService } from './projected-budget.service';

describe('ProjectedBudgetService', () => {
  let service: ProjectedBudgetService;
  let httpMock: HttpTestingController;

  const apiUrl = `${environment.apiUrl}/projected_budget`;

  const account: Account = {
    id: 1,
    label: 'Compte Courant',
    type: AccountType.COURANT,
    initialBalance: 1000,
    isActive: true,
    isDefault: true,
    position: 0,
  };

  const period: ProjectedBudgetPeriod = { id: 7, account, month: 3, year: 2026, weeksCount: 4 };

  const mockItems: ProjectedBudgetItems[] = [
    {
      id: 1,
      type: ProjectedBudgetCategoryType.INCOME,
      category: { id: 10, label: 'Salaire' },
      paymentMethod: { id: 1, label: 'Virement' },
      accountAmount: 2000,
    },
    {
      id: 2,
      type: ProjectedBudgetCategoryType.FIXED_EXPENSE,
      category: { id: 20 },
      paymentMethod: { id: 2 },
      accountAmount: 600,
      cashAmount: 0,
      comment: 'Loyer',
    },
  ];

  const mockTransactions: Transaction[] = [
    {
      id: 100,
      amount: 50,
      emissionDate: '2026-03-05',
      type: 'DEBIT',
      isAlertTriggered: false,
      isChecked: false,
      parentTransactionId: null,
      account: { id: 1 },
      category: { id: 10 },
      paymentMethod: { id: 1 },
    },
  ];

  const mockSuggested: SuggestedPeriodDataDto = {
    suggestedTransactions: mockTransactions,
    autoGeneratedItems: mockItems,
  };

  const mockInitResponse: ProjectedBudgetInitResponseDto = { period, data: mockSuggested };

  /** Copie profonde pour isoler chaque test du jeu de données partagé. */
  const clone = <T>(value: T): T => structuredClone(value);

  const serverError = { status: 500, statusText: 'Server Error' };

  beforeEach(() => {
    TestBed.configureTestingModule({
      providers: [ProjectedBudgetService, provideHttpClient(), provideHttpClientTesting()],
    });

    service = TestBed.inject(ProjectedBudgetService);
    httpMock = TestBed.inject(HttpTestingController);
  });

  afterEach(() => {
    httpMock.verify();
  });

  it('should be created', () => {
    expect(service).toBeTruthy();
  });

  describe('Initial State', () => {
    it('should start with an empty state', () => {
      expect(service.activePeriod()).toBeUndefined();
      expect(service.budgetItems()).toEqual([]);
      expect(service.toolboxTransactions()).toEqual([]);
      expect(service.isLoading()).toBe(false);
    });
  });

  describe('getProjectedBudgetItems()', () => {
    it('should GET /items with accountId, month and year and store the items', () => {
      let result: ProjectedBudgetItems[] | undefined;
      service.getProjectedBudgetItems(1, 3, 2026).subscribe((r) => (result = r));

      const req = httpMock.expectOne((r) => r.url === `${apiUrl}/items`);
      expect(req.request.method).toBe('GET');
      expect(req.request.params.get('accountId')).toBe('1');
      expect(req.request.params.get('month')).toBe('3');
      expect(req.request.params.get('year')).toBe('2026');
      req.flush(clone(mockItems));

      expect(result).toEqual(mockItems);
      expect(service.budgetItems()).toEqual(mockItems);
    });

    it('should propagate the error and leave the items unchanged on failure', () => {
      service.budgetItems.set(clone(mockItems));

      let error: HttpErrorResponse | undefined;
      service.getProjectedBudgetItems(1, 3, 2026).subscribe({ error: (e) => (error = e) });
      httpMock.expectOne((r) => r.url === `${apiUrl}/items`).flush('boom', serverError);

      expect(error?.status).toBe(500);
      expect(service.budgetItems()).toEqual(mockItems);
    });
  });

  describe('createProjectedBudgetPeriod()', () => {
    it('should POST with the clone source, fill the whole state and stop loading', () => {
      let result: ProjectedBudgetInitResponseDto | null | undefined;
      service.createProjectedBudgetPeriod(1, 3, 2026, 5).subscribe((r) => (result = r));

      // isLoading passe à true dès l'appel, avant la réponse
      expect(service.isLoading()).toBe(true);

      const req = httpMock.expectOne((r) => r.url === apiUrl);
      expect(req.request.method).toBe('POST');
      expect(req.request.body).toBeNull();
      expect(req.request.params.get('accountId')).toBe('1');
      expect(req.request.params.get('month')).toBe('3');
      expect(req.request.params.get('year')).toBe('2026');
      expect(req.request.params.get('cloneFromId')).toBe('5');
      req.flush(clone(mockInitResponse));

      expect(result).toEqual(mockInitResponse);
      expect(service.activePeriod()).toEqual(period);
      expect(service.toolboxTransactions()).toEqual(mockTransactions);
      expect(service.budgetItems()).toEqual(mockItems);
      expect(service.isLoading()).toBe(false);
    });

    it('should send an empty cloneFromId when no source period is given', () => {
      service.createProjectedBudgetPeriod(1, 3, 2026).subscribe();

      const req = httpMock.expectOne((r) => r.url === apiUrl);
      expect(req.request.params.get('cloneFromId')).toBe('');
      req.flush(clone(mockInitResponse));
    });

    it('should stop loading, propagate the error and keep the state empty on failure', () => {
      let error: HttpErrorResponse | undefined;
      service.createProjectedBudgetPeriod(1, 3, 2026).subscribe({ error: (e) => (error = e) });
      httpMock.expectOne((r) => r.url === apiUrl).flush('boom', serverError);

      expect(error?.status).toBe(500);
      expect(service.isLoading()).toBe(false);
      expect(service.activePeriod()).toBeUndefined();
      expect(service.budgetItems()).toEqual([]);
      expect(service.toolboxTransactions()).toEqual([]);
    });
  });

  describe('getAvailablePeriodsForDuplication()', () => {
    it('should GET /periods for the account without touching the state', () => {
      let result: ProjectedBudgetPeriod[] | undefined;
      service.getAvailablePeriodsForDuplication(1).subscribe((r) => (result = r));

      const req = httpMock.expectOne((r) => r.url === `${apiUrl}/periods`);
      expect(req.request.method).toBe('GET');
      expect(req.request.params.get('accountId')).toBe('1');
      req.flush([clone(period)]);

      expect(result).toEqual([period]);
      expect(service.activePeriod()).toBeUndefined();
      expect(service.budgetItems()).toEqual([]);
    });

    it('should propagate the error', () => {
      let error: HttpErrorResponse | undefined;
      service.getAvailablePeriodsForDuplication(1).subscribe({ error: (e) => (error = e) });
      httpMock.expectOne((r) => r.url === `${apiUrl}/periods`).flush('boom', serverError);

      expect(error?.status).toBe(500);
    });
  });

  describe('executeDuplicationItems()', () => {
    it('should PUT with both period ids, replace the items and stop loading', () => {
      let result: ProjectedBudgetItems[] | undefined;
      service.executeDuplicationItems(5, 7).subscribe((r) => (result = r));

      expect(service.isLoading()).toBe(true);

      const req = httpMock.expectOne((r) => r.url === `${apiUrl}/duplicateItems`);
      expect(req.request.method).toBe('PUT');
      expect(req.request.body).toBeNull();
      expect(req.request.params.get('periodIdModel')).toBe('5');
      expect(req.request.params.get('periodIdCible')).toBe('7');
      req.flush(clone(mockItems));

      expect(result).toEqual(mockItems);
      expect(service.budgetItems()).toEqual(mockItems);
      expect(service.isLoading()).toBe(false);
    });

    it('should stop loading, propagate the error and keep the items on failure', () => {
      service.budgetItems.set(clone(mockItems));

      let error: HttpErrorResponse | undefined;
      service.executeDuplicationItems(5, 7).subscribe({ error: (e) => (error = e) });
      httpMock.expectOne((r) => r.url === `${apiUrl}/duplicateItems`).flush('boom', serverError);

      expect(error?.status).toBe(500);
      expect(service.isLoading()).toBe(false);
      expect(service.budgetItems()).toEqual(mockItems);
    });
  });

  describe('fetchSuggestedTransactions()', () => {
    const flushSuggestions = (data: SuggestedPeriodDataDto) =>
      httpMock.expectOne((r) => r.url === `${apiUrl}/suggestions`).flush(clone(data));

    it('should GET /suggestions with accountId, month and year', () => {
      let result: SuggestedPeriodDataDto | undefined;
      service.fetchSuggestedTransactions(1, 3, 2026).subscribe((r) => (result = r));

      const req = httpMock.expectOne((r) => r.url === `${apiUrl}/suggestions`);
      expect(req.request.method).toBe('GET');
      expect(req.request.params.get('accountId')).toBe('1');
      expect(req.request.params.get('month')).toBe('3');
      expect(req.request.params.get('year')).toBe('2026');
      req.flush(clone(mockSuggested));

      expect(result).toEqual(mockSuggested);
    });

    it('should always update the toolbox and fill the items when they are empty', () => {
      service.fetchSuggestedTransactions(1, 3, 2026).subscribe();
      flushSuggestions(mockSuggested);

      expect(service.toolboxTransactions()).toEqual(mockTransactions);
      expect(service.budgetItems()).toEqual(mockItems);
    });

    it('should keep the items empty when the suggestions contain no generated items', () => {
      service.fetchSuggestedTransactions(1, 3, 2026).subscribe();
      flushSuggestions({ suggestedTransactions: mockTransactions, autoGeneratedItems: [] });

      expect(service.toolboxTransactions()).toEqual(mockTransactions);
      expect(service.budgetItems()).toEqual([]);
    });

    it('should NOT overwrite items that already exist', () => {
      const existing: ProjectedBudgetItems[] = [
        { ...clone(mockItems[0]), comment: 'saisi à la main' },
      ];
      service.budgetItems.set(existing);

      service.fetchSuggestedTransactions(1, 3, 2026).subscribe();
      flushSuggestions(mockSuggested);

      expect(service.budgetItems()).toEqual(existing);
      expect(service.toolboxTransactions()).toEqual(mockTransactions);
    });

    it('should propagate the error and leave the state unchanged on failure', () => {
      let error: HttpErrorResponse | undefined;
      service.fetchSuggestedTransactions(1, 3, 2026).subscribe({ error: (e) => (error = e) });
      httpMock.expectOne((r) => r.url === `${apiUrl}/suggestions`).flush('boom', serverError);

      expect(error?.status).toBe(500);
      expect(service.toolboxTransactions()).toEqual([]);
      expect(service.budgetItems()).toEqual([]);
    });
  });

  describe('saveProjectedBudgetItems()', () => {
    it('should fail without any HTTP call when there is no active period', () => {
      let error: Error | undefined;
      service.saveProjectedBudgetItems().subscribe({ error: (e) => (error = e) });

      expect(error?.message).toBe('Aucune période budgétaire active à enregistrer.');
      expect(service.isLoading()).toBe(false);
      // httpMock.verify() (afterEach) garantit qu'aucune requête n'est partie
    });

    describe('with an active period', () => {
      beforeEach(() => {
        service.activePeriod.set(clone(period));
        service.budgetItems.set(clone(mockItems));
      });

      it('should PUT the current items to the period and store the server response', () => {
        const serverItems: ProjectedBudgetItems[] = [
          { ...clone(mockItems[0]), accountAmount: 2100 },
          { ...clone(mockItems[1]), id: 99 },
        ];

        let result: ProjectedBudgetItems[] | undefined;
        service.saveProjectedBudgetItems().subscribe((r) => (result = r));

        expect(service.isLoading()).toBe(true);

        const req = httpMock.expectOne(`${apiUrl}/7/items`);
        expect(req.request.method).toBe('PUT');
        expect(req.request.body).toEqual(mockItems);
        req.flush(clone(serverItems));

        expect(result).toEqual(serverItems);
        expect(service.budgetItems()).toEqual(serverItems);
        expect(service.isLoading()).toBe(false);
      });

      it('should stop loading, propagate the error and keep the items on failure', () => {
        let error: HttpErrorResponse | undefined;
        service.saveProjectedBudgetItems().subscribe({ error: (e) => (error = e) });
        httpMock.expectOne(`${apiUrl}/7/items`).flush('boom', serverError);

        expect(error?.status).toBe(500);
        expect(service.isLoading()).toBe(false);
        expect(service.budgetItems()).toEqual(mockItems);
      });
    });
  });

  describe('deleteProjectedBudgetPeriod()', () => {
    it('should fail without any HTTP call when there is no active period', () => {
      let error: Error | undefined;
      service.deleteProjectedBudgetPeriod().subscribe({ error: (e) => (error = e) });

      expect(error?.message).toBe('Aucune période active à supprimer.');
      expect(service.isLoading()).toBe(false);
    });

    describe('with an active period', () => {
      beforeEach(() => {
        service.activePeriod.set(clone(period));
        service.budgetItems.set(clone(mockItems));
        service.toolboxTransactions.set(clone(mockTransactions));
      });

      it('should DELETE the period and reset the whole state', () => {
        let completed = false;
        service.deleteProjectedBudgetPeriod().subscribe({ complete: () => (completed = true) });

        expect(service.isLoading()).toBe(true);

        const req = httpMock.expectOne(`${apiUrl}/7`);
        expect(req.request.method).toBe('DELETE');
        req.flush(null);

        expect(completed).toBe(true);
        expect(service.activePeriod()).toBeUndefined();
        expect(service.budgetItems()).toEqual([]);
        expect(service.toolboxTransactions()).toEqual([]);
        expect(service.isLoading()).toBe(false);
      });

      it('should stop loading, propagate the error and keep the state on failure', () => {
        let error: HttpErrorResponse | undefined;
        service.deleteProjectedBudgetPeriod().subscribe({ error: (e) => (error = e) });
        httpMock.expectOne(`${apiUrl}/7`).flush('boom', serverError);

        expect(error?.status).toBe(500);
        expect(service.isLoading()).toBe(false);
        expect(service.activePeriod()).toEqual(period);
        expect(service.budgetItems()).toEqual(mockItems);
        expect(service.toolboxTransactions()).toEqual(mockTransactions);
      });
    });
  });
});
