import { ComponentFixture, TestBed } from '@angular/core/testing';
import { ProjectedBudgetToolboxComponent } from './projected-budget-toolbox.component';
import { ProjectedBudgetService } from '../projected-budget.service';
import { DashboardService } from '../../dashboards/dashboard.service';
import { ToastService } from '../../shared/ConfirmationToast/toast.service';
import { Transaction } from '../../transaction/transaction.model';
import { ProjectedBudgetCategoryType } from '../projected-budget-items.model';
import { signal, WritableSignal } from '@angular/core';
import localeFr from '@angular/common/locales/fr';
import { describe, it, expect, beforeEach, vi } from 'vitest';
import { of, throwError } from 'rxjs';
import { HttpErrorResponse } from '@angular/common/http';
import { registerLocaleData } from '@angular/common';

registerLocaleData(localeFr, 'fr-FR');

describe('ProjectedBudgetToolboxComponent', () => {
  let component: ProjectedBudgetToolboxComponent;
  let fixture: ComponentFixture<ProjectedBudgetToolboxComponent>;
  let mockProjectedBudgetService: any;
  let mockDashboardService: any;
  let mockToastService: any;

  let toolboxTransactionsSignal: WritableSignal<Transaction[]>;
  let selectedAccountIdSignal: WritableSignal<number | null>;
  let selectedMonthSignal: WritableSignal<number | null>;
  let selectedYearSignal: WritableSignal<number | null>;

  const mockTransactions = (): Transaction[] => [
    {
      id: 101,
      amount: 49.99,
      category: { id: 10, label: 'Abonnements' },
      paymentMethod: { id: 1, label: 'Prélèvement' },
    } as any,
    {
      id: 102,
      amount: 120,
      category: { id: 20, label: 'Alimentation' },
      paymentMethod: { id: 2, label: 'Carte Bancaire' },
    } as any,
  ];

  const el = (): HTMLElement => fixture.nativeElement as HTMLElement;
  const norm = (value: string | null | undefined): string =>
    (value ?? '').replace(/\s+/g, ' ').trim();
  const text = (selector: string): string => norm(el().querySelector(selector)?.textContent);

  beforeEach(() => {
    vi.spyOn(console, 'error').mockImplementation(() => {});

    toolboxTransactionsSignal = signal<Transaction[]>(mockTransactions());
    selectedAccountIdSignal = signal<number | null>(1);
    selectedMonthSignal = signal<number | null>(11);
    selectedYearSignal = signal<number | null>(2026);

    mockProjectedBudgetService = {
      toolboxTransactions: toolboxTransactionsSignal,
      fetchSuggestedTransactions: vi.fn().mockReturnValue(
        of({
          autoGeneratedItems: [{}],
          suggestedTransactions: [{}],
        }),
      ),
    };

    mockDashboardService = {
      selectedAccountId: selectedAccountIdSignal,
      selectedMonth: selectedMonthSignal,
      selectedYear: selectedYearSignal,
    };

    mockToastService = {
      show: vi.fn(),
    };

    TestBed.configureTestingModule({
      imports: [ProjectedBudgetToolboxComponent],
      providers: [
        { provide: ProjectedBudgetService, useValue: mockProjectedBudgetService },
        { provide: DashboardService, useValue: mockDashboardService },
        { provide: ToastService, useValue: mockToastService },
      ],
    });
  });

  const createComponent = async (): Promise<void> => {
    fixture = TestBed.createComponent(ProjectedBudgetToolboxComponent);
    component = fixture.componentInstance;
    fixture.detectChanges();
    await fixture.whenStable();
    fixture.detectChanges();
  };

  describe('Cycle de vie et Liaison des Signaux (Computed)', () => {
    it('should project contextual reactive filters values from dashboard parameters chains', async () => {
      await createComponent();

      expect(component['accountId']()).toBe(1);
      expect(component['month']()).toBe(11);
      expect(component['year']()).toBe(2026);
      expect(component['suggestions']()).toHaveLength(2);
    });
  });

  describe('Émission et Routage des Flux Internes (Outputs)', () => {
    it('should map manual relocation procedures and invoke dispatchRequested output signature', async () => {
      await createComponent();
      const spyEmit = vi.spyOn(component.dispatchRequested, 'emit');
      const targetTx = mockTransactions()[0];

      component.moveTransaction(targetTx, ProjectedBudgetCategoryType.FIXED_EXPENSE);

      expect(spyEmit).toHaveBeenCalledWith({
        transaction: targetTx,
        targetCategoryType: ProjectedBudgetCategoryType.FIXED_EXPENSE,
      });
    });

    it('should extract targeted element value upon HTML selector interaction changes', async () => {
      await createComponent();
      const spyMove = vi.spyOn(component, 'moveTransaction');
      const targetTx = mockTransactions()[0];

      const mockEvent = {
        target: { value: 'VARIABLE_EXPENSE' },
      } as unknown as Event;

      component.onSelectCategory(mockEvent, targetTx);
      expect(spyMove).toHaveBeenCalledWith(targetTx, ProjectedBudgetCategoryType.VARIABLE_EXPENSE);
    });
  });
  describe('Génération des Suggestions et Triggers Toast', () => {
    beforeEach(async () => {
      await createComponent();
    });

    it('should ignore suggestions updates workflows if mandatory identifiers filters are missing', () => {
      selectedAccountIdSignal.set(null);
      fixture.detectChanges();

      component.onGenerateSuggestion();
      expect(mockProjectedBudgetService.fetchSuggestedTransactions).not.toHaveBeenCalled();
    });

    it('should push success toaster notifications when dataset payloads return valid suggestions array entries', () => {
      component.onGenerateSuggestion();

      expect(mockProjectedBudgetService.fetchSuggestedTransactions).toHaveBeenCalledWith(
        1,
        11,
        2026,
      );
      expect(mockToastService.show).toHaveBeenCalledWith('Données chargées avec succès', 'success');
    });

    it('should push info toaster notifications when return collections are completely empty', () => {
      mockProjectedBudgetService.fetchSuggestedTransactions.mockReturnValue(
        of({
          autoGeneratedItems: [],
          suggestedTransactions: [],
        }),
      );

      component.onGenerateSuggestion();
      expect(mockToastService.show).toHaveBeenCalledWith('Aucune donnée à charger', 'info');
    });

    it('should route onto specialized error messages triggers when API transactions services reject calls', () => {
      mockProjectedBudgetService.fetchSuggestedTransactions.mockReturnValue(
        throwError(() => new HttpErrorResponse({ error: 'Internal Error' })),
      );

      component.onGenerateSuggestion();
      expect(mockToastService.show).toHaveBeenCalledWith(
        `Une erreur est survenue lors de la récupération des données`,
        'error',
      );
    });
  });

  describe('Intégration du Template DOM et Rendu Réel', () => {
    it('should iterate over rows and mount custom suggestion elements cards', async () => {
      await createComponent();

      const cards = el().querySelectorAll('.suggestion-card');
      expect(cards).toHaveLength(2);

      expect(text('.suggestion-card:first-of-type .suggestion-label')).toBe('Prélèvement');
      expect(text('.suggestion-card:first-of-type .suggestion-badge')).toBe('Abonnements');

      const amountText = norm(
        el().querySelector('.suggestion-card:first-of-type .suggestion-amount')?.textContent,
      ).replace(/\s+/g, '');
      expect(amountText).toContain('49,99€');
    });

    it('should clear structural grids and display placeholder screens components when collection decreases to empty', async () => {
      toolboxTransactionsSignal.set([]);
      await createComponent();

      expect(el().querySelector('.suggestion-card')).toBeNull();
      expect(el().querySelector('.toolbox-empty')).not.toBeNull();
      expect(text('.toolbox-empty')).toContain('Aucune suggestion pour ce mois');
    });
  });
});
