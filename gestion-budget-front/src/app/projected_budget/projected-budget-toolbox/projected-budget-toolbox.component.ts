import { DragDropModule } from '@angular/cdk/drag-drop';
import { CurrencyPipe } from '@angular/common';
import { HttpErrorResponse } from '@angular/common/http';
import { Component, computed, inject, output } from '@angular/core';
import { DashboardService } from '../../dashboards/dashboard.service';
import { ToastService } from '../../shared/ConfirmationToast/toast.service';
import { Transaction } from '../../transaction/transaction.model';
import { ProjectedBudgetCategoryType } from '../projected-budget-items.model';
import { ProjectedBudgetService } from '../projected-budget.service';

@Component({
  selector: 'app-projected-budget-toolbox',
  imports: [CurrencyPipe, DragDropModule],
  templateUrl: './projected-budget-toolbox.component.html',
  styleUrl: './projected-budget-toolbox.component.scss',
})
export class ProjectedBudgetToolboxComponent {
  protected budgetService = inject(ProjectedBudgetService);
  protected dashboardService = inject(DashboardService);
  private readonly toastService = inject(ToastService);
  readonly accountId = computed(() => this.dashboardService.selectedAccountId());
  readonly month = computed(() => this.dashboardService.selectedMonth());
  readonly year = computed(() => this.dashboardService.selectedYear());

  protected suggestions = this.budgetService.toolboxTransactions;

  public dispatchRequested = output<{
    transaction: Transaction;
    targetCategoryType: ProjectedBudgetCategoryType;
  }>();

  onGenerateSuggestion() {
    const currentAccount = this.accountId();
    const currentMonth = this.month();
    const currentYear = this.year();

    if (currentAccount === null || currentMonth === null) {
      return;
    }
    this.budgetService
      .fetchSuggestedTransactions(currentAccount, currentMonth, currentYear)
      .subscribe({
        next: (data) => {
          if (data.autoGeneratedItems.length != 0 || data.suggestedTransactions.length != 0)
            this.toastService.show('Données chargées avec succès', 'success');
          else this.toastService.show('Aucune donnée à charger', 'info');
        },
        error: (err: HttpErrorResponse) => {
          this.toastService.show(
            `Une erreur est survenue lors de la récupération des données`,
            'error',
          );
        },
      });
  }

  onSelectCategory(event: Event, transaction: Transaction) {
    const selectElement = event.target as HTMLSelectElement;
    const type = selectElement.value as ProjectedBudgetCategoryType;

    if (type) this.moveTransaction(transaction, type);
  }

  public moveTransaction(tx: Transaction, type: ProjectedBudgetCategoryType): void {
    this.dispatchRequested.emit({ transaction: tx, targetCategoryType: type });
  }
}
